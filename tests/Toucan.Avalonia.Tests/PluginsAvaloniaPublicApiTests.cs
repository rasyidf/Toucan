using System.Reflection;
using Toucan.Tests.Shared;
using Xunit;

namespace Toucan.Avalonia.Tests;

/// <summary>
/// The plugin packages' public surface is frozen for 1.x (V1-20). A change here breaks plugins built against the baseline in
/// <c>docs/api/</c>; see docs/compatibility.md for what may change in a minor version. To record an intended change, run the tests
/// with <c>TOUCAN_UPDATE_DOCS=1</c>, review the diff, and bump the package version.
/// </summary>
public class PluginsAvaloniaPublicApiTests
{
    public static TheoryData<string> Packages => ["Toucan.Plugins.Avalonia"];

    [Theory]
    [MemberData(nameof(Packages))]
    public void ThePublicSurfaceMatchesTheFrozenBaseline(string package)
    {
        var assembly = Assembly.Load(package);
        var root = AppContext.BaseDirectory;
        while (root != null && !File.Exists(Path.Combine(root, "Toucan.slnx"))) root = Path.GetDirectoryName(root);
        Assert.NotNull(root);
        var path = Path.Combine(root!, "docs", "api", package + ".txt");
        var version = assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion.Split('+')[0];
        var actual = $"# {package} {version}\n# Generated by PublicApiTests. Do not edit by hand.\n\n" + PublicApi.Describe(assembly);
        if (Environment.GetEnvironmentVariable("TOUCAN_UPDATE_DOCS") == "1") File.WriteAllText(path, actual);
        Assert.True(File.Exists(path), $"{path} is missing. Run the tests with TOUCAN_UPDATE_DOCS=1 to record it.");
        Assert.Equal(File.ReadAllText(path).ReplaceLineEndings("\n"), actual);
    }
}
